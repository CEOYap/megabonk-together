using System.Collections.Generic;

namespace OmniBonk.Services
{
    public enum SteamLobbyState
    {
        /// <summary>Not in a lobby and not trying to be.</summary>
        None,

        /// <summary>A create or join call is in flight, waiting on its result.</summary>
        Pending,

        /// <summary>In a lobby. <see cref="ISteamLobbyService.LobbyId"/> is valid.</summary>
        InLobby,

        /// <summary>The last operation failed. <see cref="ISteamLobbyService.DescribeStatus"/> says how.</summary>
        Failed,
    }

    /// <summary>Where a lobby-list search has got to. Independent of lobby membership.</summary>
    public enum SteamLobbySearchState
    {
        Idle,
        Searching,

        /// <summary>Finished. <see cref="ISteamLobbyService.FoundLobbyId"/> is 0 if nothing matched.</summary>
        Completed,

        Failed,
    }

    /// <summary>
    /// Steam lobbies and their key/value data.
    /// <para>IL2CPP: no <c>Callback&lt;T&gt;</c>/<c>CallResult&lt;T&gt;</c> instantiations exist for lobby
    /// types, so results are polled.</para>
    /// </summary>
    public interface ISteamLobbyService
    {
        SteamLobbyState State { get; }

        /// <summary>Poll every frame while true: the result must be read before the game's pump frees it.</summary>
        bool HasPendingCall { get; }

        SteamLobbySearchState SearchState { get; }

        ulong FoundLobbyId { get; }

        ulong LobbyId { get; }

        /// <summary>Generated by the host, read from lobby data by everyone else.</summary>
        string LobbyCode { get; }

        /// <summary>
        /// Invite accepted while the game was closed (command line). In-game accepts use a callback this install cannot receive.
        /// </summary>
        ulong LaunchLobbyId { get; }

        bool IsOwner { get; }

        ulong OwnerSteamId { get; }

        /// <summary>Asynchronous; <see cref="Poll"/> resolves it.</summary>
        void CreateLobby(int maxMembers);

        /// <summary>Asynchronous. Protocol version is checked after entering (metadata is member-only).</summary>
        void JoinLobby(ulong lobbyId);

        /// <summary>Search (filtered by code and protocol version), then join.</summary>
        void JoinByCode(string code);

        /// <summary>Joins the Steam lobby for a matchmaker room. Fails silently; only extras are lost.</summary>
        void JoinByMatchmakerCode(string code);

        /// <summary>Search without joining; result in <see cref="FoundLobbyId"/>.</summary>
        void FindLobbyByCode(string code);

        void OpenInviteOverlay();

        void LeaveLobby();

        /// <summary>Native calls: drive from an accumulator, not every frame.</summary>
        void Poll();

        bool SetLobbyData(string key, string value);

        string GetLobbyData(string key);

        /// <summary>Steam only lets a member write its own row.</summary>
        bool SetLocalMemberData(string key, string value);

        string GetMemberData(ulong steamId, string key);

        IReadOnlyList<ulong> GetMembers();

        string DescribeStatus();
    }
}
